// Deep merge: objects merge key by key, everything else (including arrays)
// replaces wholesale. An override key that is not present keeps the base value
// by construction, so content.client.js only ever has to name what changes.
function deepMerge(base, patch) {
  if (patch === undefined) return base;
  if (patch === null || typeof patch !== 'object' || Array.isArray(patch)) return patch;
  const out = Object.assign({}, base);
  for (const key of Object.keys(patch)) {
    const b = out[key];
    out[key] = (b && typeof b === 'object' && !Array.isArray(b))
      ? deepMerge(b, patch[key])
      : patch[key];
  }
  return out;
}

